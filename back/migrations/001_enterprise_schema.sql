-- Auditoria padrão em todas as tabelas de domínio
DO $$
DECLARE
    t TEXT;
    tabelas TEXT[] := ARRAY[
        'usuarios', 'clientes', 'nail_designs', 'administradores',
        'modelos_unhas', 'programacao_semanal', 'status_pagamentos',
        'agendamentos'
    ];
BEGIN
    FOREACH t IN ARRAY tabelas LOOP
        BEGIN
            EXECUTE format(
                'ALTER TABLE %I ADD COLUMN IF NOT EXISTS "created_at" '
                'TIMESTAMPTZ NOT NULL DEFAULT now()', t
            );
            EXECUTE format(
                'ALTER TABLE %I ADD COLUMN IF NOT EXISTS "updated_at" '
                'TIMESTAMPTZ NOT NULL DEFAULT now()', t
            );
        EXCEPTION WHEN others THEN
            RAISE NOTICE 'Auditoria pulada em %: %', t, SQLERRM;
        END;
    END LOOP;
END $$;

