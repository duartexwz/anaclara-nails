-- ---------------------------------------------------------------------
-- 7. SEED DE STATUS (o backend espera Pendente/Pago/Cancelado)
-- Sem ON CONFLICT: bancos legados podem não ter UNIQUE em nome.
-- ---------------------------------------------------------------------
DO $$
BEGIN
    BEGIN
        ALTER TABLE "status_pagamentos"
            ADD CONSTRAINT "uq_status_pagamentos_nome" UNIQUE ("nome");
    EXCEPTION WHEN duplicate_object THEN
        -- já existe
    WHEN others THEN
        RAISE NOTICE 'UNIQUE de status pulada (duplicados legados?): %', SQLERRM;
    END;

    INSERT INTO "status_pagamentos" ("nome")
    SELECT s.nome FROM (VALUES ('Pendente'), ('Pago'), ('Cancelado')) AS s(nome)
    WHERE NOT EXISTS (
        SELECT 1 FROM "status_pagamentos" sp WHERE sp.nome = s.nome
    );
END $$;
