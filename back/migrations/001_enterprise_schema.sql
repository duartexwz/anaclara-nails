-- ---------------------------------------------------------------------
-- 5. FKs LEGADAS ERRADAS → FKs NOMEADAS CORRETAS
-- Remove FKs auto-nomeadas herdadas da modelagem antiga e recria no
-- padrão fk_<tabela>_<coluna> apontando para a tabela/coluna certas.
-- ---------------------------------------------------------------------
DO $$
DECLARE
    fk TEXT;
    tbl TEXT;
    fks_legadas TEXT[] := ARRAY[
        'usuarios_email_fkey',
        'clientes_email_id_fkey',
        'clientes_id_fkey',
        'modelos_unhas_id_fkey',
        'status_pagamentos_id_fkey',
        'nails_id_fkey',
        'fk_administradores_type_user',
        'fk_usuarios_type_user'
    ];
BEGIN
    FOREACH fk IN ARRAY fks_legadas LOOP
        SELECT c.relname INTO tbl FROM pg_constraint k
        JOIN pg_class c ON c.oid = k.conrelid
        WHERE k.conname = fk LIMIT 1;
        IF tbl IS NOT NULL THEN
            BEGIN
                EXECUTE format(
                    'ALTER TABLE %I DROP CONSTRAINT %I', tbl, fk
                );
            EXCEPTION WHEN others THEN
                RAISE NOTICE 'FK % pulada: %', fk, SQLERRM;
            END;
        END IF;
    END LOOP;
END $$;

-- Recria as FKs no padrão (só se coluna e alvo existirem eTipos)
DO $$
BEGIN
    -- usuarios.type_user_id → type_users(id)
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_usuarios_type_user_id'
    ) THEN
        ALTER TABLE "usuarios" ADD CONSTRAINT "fk_usuarios_type_user_id"
            FOREIGN KEY ("type_user_id") REFERENCES "type_users" ("id")
            ON UPDATE NO ACTION ON DELETE RESTRICT;
    END IF;

    -- administradores.type_user_id → type_users(id)
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_administradores_type_user_id'
    ) THEN
        ALTER TABLE "administradores"
            ADD CONSTRAINT "fk_administradores_type_user_id"
            FOREIGN KEY ("type_user_id") REFERENCES "type_users" ("id")
            ON UPDATE NO ACTION ON DELETE RESTRICT;
    END IF;

    -- administradores.nail_design_id → nail_designs(id)
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_administradores_nail_design_id'
    ) THEN
        ALTER TABLE "administradores"
            ADD CONSTRAINT "fk_administradores_nail_design_id"
            FOREIGN KEY ("nail_design_id") REFERENCES "nail_designs" ("id")
            ON UPDATE NO ACTION ON DELETE SET NULL;
    END IF;

    -- programacao_semanal.profissional_id → nail_designs(id)
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_programacao_semanal_profissional_id'
    ) THEN
        ALTER TABLE "programacao_semanal"
            ADD CONSTRAINT "fk_programacao_semanal_profissional_id"
            FOREIGN KEY ("profissional_id")
            REFERENCES "nail_designs" ("id")
            ON UPDATE NO ACTION ON DELETE CASCADE;
    END IF;

    -- agendamentos.cliente_id → clientes(id)
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_agendamentos_cliente_id'
    ) THEN
        ALTER TABLE "agendamentos" ADD CONSTRAINT "fk_agendamentos_cliente_id"
            FOREIGN KEY ("cliente_id") REFERENCES "clientes" ("id")
            ON UPDATE NO ACTION ON DELETE RESTRICT;
    END IF;

    -- agendamentos.modelo_id → modelos_unhas(id)
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_agendamentos_modelo_id'
    ) THEN
        ALTER TABLE "agendamentos" ADD CONSTRAINT "fk_agendamentos_modelo_id"
            FOREIGN KEY ("modelo_id") REFERENCES "modelos_unhas" ("id")
            ON UPDATE NO ACTION ON DELETE RESTRICT;
    END IF;

    -- agendamentos.status_pagamentos_id → status_pagamentos(id)
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_agendamentos_status_pagamentos_id'
    ) THEN
        ALTER TABLE "agendamentos"
            ADD CONSTRAINT "fk_agendamentos_status_pagamentos_id"
            FOREIGN KEY ("status_pagamentos_id")
            REFERENCES "status_pagamentos" ("id")
            ON UPDATE NO ACTION ON DELETE RESTRICT;
    END IF;
EXCEPTION WHEN others THEN
    RAISE NOTICE 'FKs parcialmente aplicadas (dados legados?): %', SQLERRM;
END $$;

